export function getProjectStory(project) {
  if (projectStories[project.name]) return projectStories[project.name];
  const [lead = '', ...paragraphs] = (project.details || project.description || '').split(/\n\s*\n/).filter(Boolean);
  return {
    layout: 'feature',
    gallery: 'pair',
    lead,
    sections: paragraphs.length ? [{ heading: 'The work', paragraphs }] : [],
  };
}
